import { useEffect } from "react";

interface Props {
  /** 未出題の新規を1日に何件までキューへ入れるか。日次キューの状態が読めないときは既定値を出す。 */
  newLimit: number;
  /** 開いたときに表示する節のid（整理ページの「使い方」なら help-organize）。 */
  section?: string | null;
  /** 戻り先の名前（「整理ページへ戻る」など）。 */
  backLabel?: string;
  onExit: () => void;
}

const SECTIONS = [
  { id: "help-today", title: "今日の学習" },
  { id: "help-schedule", title: "出題の仕組み" },
  { id: "help-progress", title: "学習の進み具合" },
  { id: "help-speaking", title: "英会話練習" },
  { id: "help-card", title: "習熟度と優先度" },
  { id: "help-organize", title: "問い・示唆・タグ" },
] as const;

/**
 * 画面には数字と操作だけを出し、仕組みや定義の説明はこのページにまとめる。
 * 画面の文言を変えたら、ここも合わせて直す。
 */
export function HelpView({ newLimit, section = null, backLabel = "ダッシュボードへ戻る", onExit }: Props) {
  useEffect(() => {
    if (section) document.getElementById(section)?.scrollIntoView();
  }, [section]);

  return (
    <div className="quiz-page help-page">
      <header className="quiz-header">
        <button className="text-button" onClick={onExit}>← {backLabel}</button>
      </header>
      <main className="help-body">
        <h1>ヘルプ</h1>
        <nav className="help-toc" aria-label="目次">
          {SECTIONS.map((section) => <a key={section.id} href={`#${section.id}`}>{section.title}</a>)}
        </nav>

        <section id="help-today" aria-labelledby="help-today-title">
          <h2 id="help-today-title">今日の学習</h2>
          <dl>
            <dt>今すぐ解ける</dt>
            <dd>期限が来て、問題が用意できている数です。「期限超過」は予定日を過ぎたもの、「再学習」は外してすぐにやり直すものです。</dd>
            <dt>今日の回答</dt>
            <dd>今日答えた問題数と正答率です。</dd>
            <dt>見直す講評</dt>
            <dd>外した問題（不正解・部分正解）のうち、まだ講評を確認していない数です。正解した問題の講評は確認しなくてかまいません。</dd>
          </dl>
          <p>復習はキューの上から順に、問題がある限り解き続けられます。答えた分はその都度記録されるので、途中で終えても大丈夫です。</p>
          <p>「カテゴリを選んで復習」では、登録済みのカテゴリから1つを選べます。「すべてのカテゴリ」で通常の復習に戻せます。選んだカテゴリのうち、期限が来て問題が用意できているものだけを、いつもの優先順で出題します。追加の問題を受け取るときも同じカテゴリを使います。対象の問題がなければ、そのカテゴリの復習を終了します。</p>
          <p>通常の復習と同じ問題・学習ログ・復習予定を使います。回答したカードは通常の復習にも反映されます。カテゴリを選んだだけでは問題生成・採点・予定の前倒しを行いません。キューの件数と「今すぐ問題を作る」は全カテゴリが対象です。</p>
        </section>

        <section id="help-schedule" aria-labelledby="help-schedule-title">
          <h2 id="help-schedule-title">出題の仕組み</h2>
          <p>問題は30分ごとに、期限が来たナレッジの分をまとめて作ります。回答は1時間ごとに自動で採点され、外した問題の講評は「見直す講評」から確認できます。</p>
          <p>次回までの基準間隔は、q0=10分、q1=30分、q2=6時間、q3=12時間、q4=2日以上、q5=4日以上です。q4・q5は覚えていられた期間に応じて伸び（q4は2倍、q5は2.8倍）、q0〜q3は段階ごとの時刻に戻ります。</p>
          <p>正解・不正解にかかわらず、次回までの間隔には優先度の倍率がかかります（最高0.5・高1・中1.5・低2・最低3倍）。</p>
          <p>まだ出題していない新規のナレッジは、1日{newLimit}件までキューに入ります。超えた分は「今すぐ解ける」に数えず、翌日以降に回します。15件のうち通常の期限到来が5件以上あれば、再学習は最大10件です。</p>
        </section>

        <section id="help-progress" aria-labelledby="help-progress-title">
          <h2 id="help-progress-title">学習の進み具合</h2>
          <p>登録した件数ではなく、どれだけ覚えていられるかで進み具合を見ます。</p>
          <dl>
            <dt>記憶のもち</dt>
            <dd>次に忘れるまでの見込み期間ごとに、カードの枚数を数えます。未出題のカードは、出題されるとどれかの期間に入ります。</dd>
            <dt>復習の正答率（週別）</dt>
            <dd>2回目以降の出題だけで計算します。新しく覚える分は含めません。今週の棒は集計途中なので斜線で示します。</dd>
            <dt>その他のグラフ</dt>
            <dd>登録数の推移・習熟度の推移・カテゴリ別分布・習熟度分布です。毎日見る必要はないので折りたたんでいます。</dd>
          </dl>
        </section>

        <section id="help-speaking" aria-labelledby="help-speaking-title">
          <h2 id="help-speaking-title">英会話練習</h2>
          <p>英語のナレッジを使って、瞬間英作文とフレーズの音読を練習します。「候補」は練習に使える英語のナレッジの数です。練習の結果は復習の進み具合（習熟度や次回の復習日）には影響しません。</p>
          <p>例文が一部だけ作れた場合は、用意できた件数で練習を始めるか、不足分だけ再試行できます。再試行が失敗しても、作成済みの例文は残ります。「条件を選び直す」を押した場合は、新しい条件で作り直します。</p>
        </section>

        <section id="help-card" aria-labelledby="help-card-title">
          <h2 id="help-card-title">習熟度と優先度</h2>
          <dl>
            <dt>習熟度</dt>
            <dd>未学習 → 学習中 → 習得中 → 定着 の4段階です。主に回答の結果に応じて変わります。</dd>
            <dt>優先度</dt>
            <dd>最高・高・中・低・最低の5段階です。同じ期限の中での出題順と、次回までの間隔の倍率に使います。</dd>
          </dl>
        </section>

        <section id="help-organize" aria-labelledby="help-organize-title">
          <h2 id="help-organize-title">問い・示唆・タグ</h2>
          <p>ナレッジから「自分にとってどう役立つか」を示唆に書き、示唆を分野をまたぐ問いで束ねます。</p>
          <dl>
            <dt>カテゴリ</dt>
            <dd>分野です。1つのナレッジに1つ付けます（英語・ビジネスなど）。</dd>
            <dt>タグ</dt>
            <dd>分野の中の小分類や出典です。複数付けられます（#単語・#読書など）。</dd>
            <dt>問い</dt>
            <dd>分野をまたいで示唆を束ねる「何を判断したいか」です。</dd>
            <dt>ノート</dt>
            <dd>問いやテーマ（自動タグ）ごとに、ナレッジ・示唆・日記をまとめて読むページです。</dd>
          </dl>
          <p>整理ページで読んだり整理したりしても、復習の記録や次回の復習日は変わりません。</p>

          <h3>問い</h3>
          <p>「何を判断したいか」を問いとして立てると、意味の近い示唆・ナレッジ・日記をAIが集めます。まず自分で答えを考え、次に材料を開いて確かめます。</p>
          <p>「AIが集めた材料」には、問い文に意味が近いもの（近さ0.45以上）が並びます。合わないものを「外す」と、その問いには二度と出ません。</p>

          <h3>示唆</h3>
          <p>ナレッジごとに残した「自分にとってどう役立つか」のメモです。出題や採点には使いません。</p>
          <p>示唆や日記の「行動をInboxへ」から、次にする行動を500文字以内で書けます。「Inboxに登録」を押すと、元の本文（最大1,000文字）と出典を添えてIdeaの未整理Inboxへ保存します。AIは呼びません。Inboxの「行動元」リンクで現在の示唆・日記を確認でき、元が編集・削除されても登録時の引用はInboxに残ります。行動はInboxからToDoなどへ整理できます。</p>
          <p>「AIで共通点をまとめる」でAIに送るのは、新しい順に最大300件の示唆とナレッジ名・カテゴリだけです。まとめは保存され、同じ入力と分析条件なら、画面を離れて戻っても前回の結果を表示します。表示するだけではAIを呼びません。入力や分析条件が変わった場合は古い結果を表示せず、「AIで共通点をまとめる」で新しく分析できます。同じ入力で作り直すときは「再分析」を押します。「この問いとして保存」を押したテーマだけが問いになります。</p>

          <h3>タグ</h3>
          <p>タグからナレッジを探せます。カテゴリで絞り込むと、そのカテゴリのナレッジだけで集計します。</p>

          <h3>ノート</h3>
          <p>問いやテーマを選ぶと、集まったナレッジ・示唆・日記を1枚のノートとして読めます。テーマは自動タグで、そのタグのナレッジと、意味の近い示唆・日記が集まります。合わないものを「外す」と、そのノートには二度と出ません。</p>
        </section>
      </main>
    </div>
  );
}
