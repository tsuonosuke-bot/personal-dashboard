-- Review queue: questions are generated in scheduled batches and answers are
-- graded in scheduled batches, instead of calling the AI on every request.
--
-- * review_queue holds one question per row through its whole life:
--   ready (generated, waiting to be served) -> answered (waiting for grading)
--   -> grading -> graded, or error after repeated grading failures, or
--   discarded when the knowledge changed or was answered through another path.
-- * At most one active (ready/answered/grading/error) question exists per card.
-- * quiz_log keeps the official record and now also stores the question, the
--   answer, the model answer and the feedback so the learning log can show them.
-- * Scheduling uses the time of the answer, not the time of grading.
begin;

create table if not exists public.review_queue (
  id bigint generated by default as identity primary key,
  knowledge_id uuid not null references public.knowledge(id) on delete cascade,
  content_version bigint not null,
  format text not null check (format in ('一問一答', '四択', '記述説明', '産出')),
  question text not null check (char_length(btrim(question)) between 1 and 2000),
  choices jsonb,
  correct_choice text,
  -- Feedback prepared at generation time so a multiple-choice answer can be
  -- recorded instantly without another AI call.
  prepared_explanation text check (prepared_explanation is null or char_length(prepared_explanation) <= 2000),
  status text not null default 'ready'
    check (status in ('ready', 'answered', 'grading', 'graded', 'error', 'discarded')),
  generated_at timestamptz not null default now(),
  answer_text text check (answer_text is null or char_length(answer_text) <= 2000),
  answered_at timestamptz,
  grade_attempts smallint not null default 0 check (grade_attempts >= 0),
  grading_started_at timestamptz,
  last_error text,
  graded_at timestamptz,
  discarded_reason text,
  constraint review_queue_choice_shape check (
    (format = '四択' and jsonb_typeof(choices) = 'array' and jsonb_array_length(choices) = 4
      and correct_choice is not null and choices ? correct_choice)
    or (format <> '四択' and choices is null and correct_choice is null)
  ),
  constraint review_queue_answer_shape check (
    status in ('ready', 'discarded') or (answered_at is not null and answer_text is not null)
  )
);

create unique index if not exists review_queue_one_active_per_knowledge
  on public.review_queue (knowledge_id)
  where status in ('ready', 'answered', 'grading', 'error');
create index if not exists review_queue_status_idx
  on public.review_queue (status, generated_at);

alter table public.review_queue enable row level security;
revoke all on table public.review_queue from public, anon, authenticated;
grant select, insert, update, delete on table public.review_queue to service_role;

comment on table public.review_queue is
  'Pre-generated review questions and pending answers. One active row per knowledge card.';

