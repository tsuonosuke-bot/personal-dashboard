-- Send the scheduled review generation and grading through the Anthropic
-- Message Batches API (half the token price).
--
-- Batch results arrive asynchronously, so a scheduled run submits a batch and a
-- later run collects it. review_ai_batches remembers each submitted batch with
-- what the collecting run needs (the generation candidates or the grading
-- answers). While a grading batch is pending, its answers stay in 'grading':
-- claim_review_answers no longer returns them to 'answered' after 10 minutes,
-- so they are neither graded twice nor counted as another attempt. A batch older
-- than 25 hours has expired on the API side and no longer protects its answers.
--
-- Candidate picking moves to pick_review_generation_candidates_ahead, which
-- leaves out cards in a pending generation batch before its LIMIT (otherwise
-- they would fill the top of every pick until collected), counts their new
-- cards against the daily new-card allowance, and takes the look-ahead window:
-- scheduled runs look further ahead because their questions arrive one run
-- later. pick_review_generation_candidates keeps its signature and calls it
-- with the old 30 minutes, so the app build deployed before this keeps working
-- (nothing is removed, and no overload makes two-argument calls ambiguous).
begin;

create table if not exists public.review_ai_batches (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('generate', 'grade')),
  provider_batch_id text not null unique check (char_length(provider_batch_id) between 1 and 200),
  status text not null default 'pending' check (status in ('pending', 'collected', 'failed')),
  -- generate: the candidate cards. grade: empty.
  knowledge_ids uuid[] not null default '{}',
  -- grade: the claimed review_queue rows. generate: empty.
  item_ids bigint[] not null default '{}',
  payload jsonb not null,
  note text check (note is null or char_length(note) <= 1000),
  created_at timestamptz not null default now(),
  finished_at timestamptz
);

comment on table public.review_ai_batches is
  'Anthropic Message Batches submitted by the scheduled review generation/grading runs and not yet (or already) collected.';

create index if not exists review_ai_batches_pending_idx
  on public.review_ai_batches (kind, created_at) where status = 'pending';

alter table public.review_ai_batches enable row level security;
revoke all on table public.review_ai_batches from public, anon, authenticated;
grant select, insert, update, delete on table public.review_ai_batches to service_role;

create or replace function public.register_review_ai_batch(
  p_kind text,
  p_provider_batch_id text,
  p_knowledge_ids uuid[],
  p_item_ids bigint[],
  p_payload jsonb
)
returns bigint
language plpgsql
set search_path to 'public', 'pg_temp'
as $$
declare
  v_id bigint;
begin
  delete from public.review_ai_batches
  where status <> 'pending' and created_at < now() - interval '30 days';

  insert into public.review_ai_batches (kind, provider_batch_id, knowledge_ids, item_ids, payload)
  values (p_kind, p_provider_batch_id, coalesce(p_knowledge_ids, '{}'), coalesce(p_item_ids, '{}'), p_payload)
  returning id into v_id;
  return v_id;
end
$$;

create or replace function public.list_pending_review_ai_batches(p_kind text)
returns table(
  id bigint,
  provider_batch_id text,
  knowledge_ids uuid[],
  item_ids bigint[],
  payload jsonb,
  created_at timestamptz
)
language sql
stable
set search_path to 'public', 'pg_temp'
as $$
  select b.id, b.provider_batch_id, b.knowledge_ids, b.item_ids, b.payload, b.created_at
  from public.review_ai_batches b
  where b.kind = p_kind and b.status = 'pending'
  order by b.created_at, b.id;
$$;

-- Only a pending batch can be finished, so a batch is collected at most once.
create or replace function public.finish_review_ai_batch(p_id bigint, p_status text, p_note text)
returns boolean
language plpgsql
set search_path to 'public', 'pg_temp'
as $$
begin
  if p_status not in ('collected', 'failed') then
    raise exception 'invalid review ai batch status %', p_status using errcode = '22023';
  end if;
  update public.review_ai_batches b
  set status = p_status, note = left(p_note, 1000), finished_at = now()
  where b.id = p_id and b.status = 'pending';
  return found;
end
$$;

-- Same as 20261002100000_review_queue.sql, except that answers waiting in a
-- pending grading batch are not returned to 'answered' after 10 minutes.
create or replace function public.claim_review_answers(p_limit integer default 30)
returns table(
  id bigint,
  knowledge_id uuid,
  format text,
  question text,
  choices jsonb,
  correct_choice text,
  prepared_explanation text,
  answer_text text,
  answered_at timestamptz,
  grade_attempts smallint
)
language plpgsql
set search_path to 'public', 'pg_temp'
as $$
begin
  update public.review_queue q
  set status = 'answered', grading_started_at = null
  where q.status = 'grading' and q.grading_started_at < now() - interval '10 minutes'
    and not exists (
      select 1 from public.review_ai_batches b
      where b.kind = 'grade' and b.status = 'pending'
        and b.created_at > now() - interval '25 hours'
        and q.id = any(b.item_ids)
    );

  return query
  with claimed as (
    select q.id from public.review_queue q
    where q.status = 'answered'
    order by q.answered_at, q.id
    limit greatest(1, least(coalesce(p_limit, 30), 30))
    for update skip locked
  )
  update public.review_queue q
  set status = 'grading', grading_started_at = now(), grade_attempts = q.grade_attempts + 1
  from claimed c
  where q.id = c.id
  returning q.id, q.knowledge_id, q.format, q.question, q.choices, q.correct_choice,
    q.prepared_explanation, q.answer_text, q.answered_at, q.grade_attempts;
end
$$;

-- The body of pick_review_generation_candidates in
-- 20261004120000_review_generation_holds.sql, except that cards in a pending
-- generation batch (younger than 25 hours) count as active, and the look-ahead
-- window is a parameter (30 minutes before this, clamped to 0-180).
create or replace function public.pick_review_generation_candidates_ahead(
  p_limit integer,
  p_relearning_only boolean,
  p_lookahead_minutes integer
)
returns table(
  id uuid,
  title text,
  explanation text,
  category text,
  tags text[],
  mastery text,
  times_asked integer,
  pool text,
  stability_hours numeric,
  relearning_stage text,
  content_version bigint
)
language sql
stable
set search_path to 'public', 'pg_temp'
as $$
  with active as (
    select q.knowledge_id
    from public.review_queue q
    where q.status in ('ready', 'answered', 'grading', 'error')
    union
    select unnest(b.knowledge_ids)
    from public.review_ai_batches b
    where b.kind = 'generate' and b.status = 'pending' and b.created_at > now() - interval '25 hours'
  ),
  new_in_queue as (
    select count(*)::integer as n
    from active a
    join public.knowledge k on k.id = a.knowledge_id
    where k.times_asked = 0
  ),
  allowance as (
    select greatest(0, public.review_new_cards_remaining_today() - (select n from new_in_queue)) as new_slots
  ),
  eligible as (
    select
      k.*,
      case
        when k.relearning_stage is not null then 'R'::text
        when k.times_asked = 0 then 'B'::text
        else 'A'::text
      end as pool
    from public.knowledge k
    where k.archived = false
      and k.next_review_at <= now() + make_interval(mins => greatest(0, least(coalesce(p_lookahead_minutes, 30), 180)))
      and not exists (select 1 from active a where a.knowledge_id = k.id)
      and not exists (
        select 1 from public.review_generation_holds h
        where h.knowledge_id = k.id and h.content_version = k.content_version and h.retry_after > now()
      )
  ),
  new_ranked as (
    select e.id, row_number() over (
      order by
        case e.priority when '最高' then 0 when '高' then 1 when '中' then 2 when '低' then 3 else 4 end,
        e.created_at,
        e.id
    ) as rank_no
    from eligible e
    where e.pool = 'B'
  ),
  selectable as (
    select e.*
    from eligible e
    where (not p_relearning_only or e.pool = 'R')
      and (
        e.pool <> 'B'
        or e.id in (select n.id from new_ranked n cross join allowance a where n.rank_no <= a.new_slots)
      )
  )
  select
    s.id, s.title, s.explanation, s.category, s.tags, s.mastery, s.times_asked, s.pool,
    s.stability_hours, s.relearning_stage, s.content_version
  from selectable s
  order by
    case s.pool when 'R' then 0 when 'A' then 1 else 2 end,
    case when s.pool = 'R' then s.relearning_quality else 4 end asc nulls last,
    case s.priority when '最高' then 0 when '高' then 1 when '中' then 2 when '低' then 3 else 4 end,
    s.next_review_at,
    s.id
  limit greatest(0, least(coalesce(p_limit, 30), public.review_generation_batch_size()));
$$;

create or replace function public.pick_review_generation_candidates(
  p_limit integer default 30,
  p_relearning_only boolean default false
)
returns table(
  id uuid,
  title text,
  explanation text,
  category text,
  tags text[],
  mastery text,
  times_asked integer,
  pool text,
  stability_hours numeric,
  relearning_stage text,
  content_version bigint
)
language sql
stable
set search_path to 'public', 'pg_temp'
as $$
  select * from public.pick_review_generation_candidates_ahead(p_limit, p_relearning_only, 30);
$$;

do $$
declare
  fn text;
begin
  foreach fn in array array[
    'public.register_review_ai_batch(text, text, uuid[], bigint[], jsonb)',
    'public.list_pending_review_ai_batches(text)',
    'public.finish_review_ai_batch(bigint, text, text)',
    'public.claim_review_answers(integer)',
    'public.pick_review_generation_candidates_ahead(integer, boolean, integer)',
    'public.pick_review_generation_candidates(integer, boolean)'
  ]
  loop
    execute format('revoke all on function %s from public, anon, authenticated', fn);
    execute format('grant execute on function %s to service_role', fn);
  end loop;
end
$$;

