-- SF6 redesign, phase 1 of 2 (#184-#187): adds the situation master, the sequence master (combos and set plays in
-- one table), their child tables and the frame data tables, then copies the existing combos / set plays into them.
-- Nothing is dropped here, so the previous screen keeps working until the new code is deployed.
-- Phase 2 (202610120003_sf6_drop_legacy.sql) removes the old tables after the new screen is confirmed in production.
-- Only the Hub's server-side API (service_role) reads and writes these tables.

-- ① situations: triggers (how a sequence starts, no numbers) and states (frame advantage / position / knockdown)
create table if not exists public.sf6_situations (
  id bigint generated by default as identity primary key,
  character text check (character is null or char_length(character) between 1 and 40),
  kind text not null check (kind in ('trigger', 'state')),
  name text not null check (char_length(name) between 1 and 60),
  preset_key text unique check (preset_key is null or preset_key ~ '^[a-z_]{1,30}$'),
  advantage smallint check (advantage is null or advantage between -99 and 300),
  position text not null default 'anywhere' check (position in ('anywhere', 'midscreen', 'corner')),
  recovery text check (recovery is null or recovery in ('back_roll', 'no_back_roll', 'none')),
  memo text check (memo is null or char_length(memo) between 1 and 2000),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sf6_situations_trigger_shape check (kind <> 'trigger' or (advantage is null and recovery is null and position = 'anywhere')),
  constraint sf6_situations_state_shape check (kind <> 'state' or (advantage is not null and character is not null))
);
-- A state is reused whenever character / advantage / position / knockdown match (find-or-create on save).
create unique index if not exists sf6_situations_state_key
  on public.sf6_situations (character, advantage, position, (coalesce(recovery, ''))) where kind = 'state';
create unique index if not exists sf6_situations_trigger_name
  on public.sf6_situations ((coalesce(character, '')), name) where kind = 'trigger';
create index if not exists sf6_situations_character_idx on public.sf6_situations (character, kind, archived);

-- ② sequences: combos and set plays
create table if not exists public.sf6_sequences (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('combo', 'setplay')),
  character text not null check (char_length(character) between 1 and 40),
  title text not null check (char_length(title) between 1 and 120),
  notation text not null check (char_length(notation) between 1 and 1000),
  startup smallint check (startup is null or startup between 1 and 99),
  damage integer check (damage is null or damage between 0 and 20000),
  drive_cost numeric(2,1) not null default 0 check (drive_cost between 0 and 6 and drive_cost * 2 = trunc(drive_cost * 2)),
  sa_cost smallint not null default 0 check (sa_cost between 0 and 4),
  position text not null default 'anywhere' check (position in ('anywhere', 'midscreen', 'corner')),
  layering text check (layering is null or layering in ('meaty', 'safe_jump', 'other')),
  aim text check (aim is null or aim in ('strike', 'throw', 'shimmy')),
  end_purpose text check (end_purpose is null or end_purpose in ('damage', 'oki', 'carry')),
  mastery smallint not null default 0 check (mastery between 0 and 3),
  memo text check (memo is null or char_length(memo) between 1 and 2000),
  archived boolean not null default false,
  -- Dropped in phase 2. No foreign keys to the old tables, so they can be dropped.
  legacy_combo_id bigint unique,
  legacy_setplay_id bigint unique,
  legacy_copied_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sf6_sequences_kind_shape check (
    (kind = 'setplay' and aim is not null and end_purpose is null)
    or (kind = 'combo' and aim is null and layering is null)
  )
);
create index if not exists sf6_sequences_character_idx on public.sf6_sequences (character, kind, archived, created_at);

-- ③ where a sequence starts (many to many)
create table if not exists public.sf6_sequence_starts (
  sequence_id bigint not null references public.sf6_sequences(id) on delete cascade,
  situation_id bigint not null references public.sf6_situations(id) on delete cascade,
  primary key (sequence_id, situation_id)
);
create index if not exists sf6_sequence_starts_situation_idx on public.sf6_sequence_starts (situation_id);

-- ④ result -> next situation
create table if not exists public.sf6_sequence_results (
  id bigint generated by default as identity primary key,
  sequence_id bigint not null references public.sf6_sequences(id) on delete cascade,
  kind text not null check (kind in ('hit', 'guard', 'opponent')),
  opponent_action text check (opponent_action is null or opponent_action in
    ('reversal', 'backdash', 'jump', 'tech', 'delay_tech', 'parry', 'drive_reversal', 'back_roll')),
  outcome text check (outcome is null or outcome in ('win', 'lose', 'unknown')),
  next_situation_id bigint references public.sf6_situations(id) on delete set null,
  constraint sf6_sequence_results_shape check (
    (kind = 'opponent') = (opponent_action is not null)
    and (kind <> 'opponent' or outcome is not null)
  )
);
create unique index if not exists sf6_sequence_results_key
  on public.sf6_sequence_results (sequence_id, kind, (coalesce(opponent_action, '')));
create index if not exists sf6_sequence_results_next_idx on public.sf6_sequence_results (next_situation_id);

