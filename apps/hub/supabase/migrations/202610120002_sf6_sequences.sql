-- p_ref: a situation id (number) or {"state": {"advantage", "position", "recovery", "name"}}.
-- A state is found or created by character/advantage/position/recovery; an existing state keeps its name.
create or replace function public.sf6_resolve_situation(p_character text, p_ref jsonb)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_id bigint;
  v_state jsonb;
  v_advantage smallint;
  v_position text;
  v_recovery text;
  v_name text;
begin
  if jsonb_typeof(p_ref) = 'number' then
    v_id := (p_ref #>> '{}')::bigint;
    if not exists (select 1 from public.sf6_situations where id = v_id) then
      raise exception 'SF6_SITUATION_MISSING';
    end if;
    return v_id;
  end if;
  v_state := p_ref -> 'state';
  if jsonb_typeof(v_state) is distinct from 'object' or jsonb_typeof(v_state -> 'advantage') is distinct from 'number' then
    raise exception 'SF6_SITUATION_INVALID';
  end if;
  v_advantage := (v_state ->> 'advantage')::smallint;
  v_position := coalesce(v_state ->> 'position', 'anywhere');
  v_recovery := v_state ->> 'recovery';
  v_name := nullif(btrim(coalesce(v_state ->> 'name', '')), '');
  if v_name is null then
    -- e.g. "+29F 画面端 後ろ受け身可" (same wording as stateLabel in public/sf6-plan.js)
    v_name := concat_ws(' ',
      case when v_advantage > 0 then '+' else '' end || v_advantage || 'F',
      case v_position when 'midscreen' then '画面中央' when 'corner' then '画面端' end,
      case v_recovery when 'back_roll' then '後ろ受け身可' when 'no_back_roll' then '後ろ受け身不可' when 'none' then 'ダウンなし' end);
  end if;
  insert into public.sf6_situations (character, kind, name, advantage, position, recovery)
  values (p_character, 'state', left(v_name, 60), v_advantage, v_position, v_recovery)
  on conflict (character, advantage, position, (coalesce(recovery, ''))) where kind = 'state'
  do update set archived = false, updated_at = now()
  returning id into v_id;
  return v_id;
end;
$$;

-- Saves a sequence with its starts and results in one transaction.
--   p_id null: insert. Otherwise update, locked on p_updated_at (SF6_CONFLICT when it changed).
--   p_row: columns by name (jsonb_populate_record); keys that are not sent keep their current value on update.
--   p_starts / p_results: null keeps the current children; an array replaces them.
--     starts:  [situation ref, ...]
--     results: [{"kind", "opponent_action", "outcome", "next": situation ref | null}, ...]
create or replace function public.sf6_save_sequence(
  p_id bigint,
  p_updated_at timestamptz,
  p_row jsonb,
  p_starts jsonb,
  p_results jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_old public.sf6_sequences%rowtype;
  v_new public.sf6_sequences%rowtype;
  v_id bigint;
  v_ref jsonb;
  v_result jsonb;
begin
  if p_id is null then
    if p_starts is null then
      raise exception 'SF6_STARTS_REQUIRED';
    end if;
    v_new := jsonb_populate_record(null::public.sf6_sequences, p_row);
    insert into public.sf6_sequences (
      kind, character, title, notation, startup, damage, drive_cost, sa_cost, position,
      layering, aim, end_purpose, mastery, memo, archived
    ) values (
      v_new.kind, v_new.character, v_new.title, v_new.notation, v_new.startup, v_new.damage,
      coalesce(v_new.drive_cost, 0), coalesce(v_new.sa_cost, 0), coalesce(v_new.position, 'anywhere'),
      v_new.layering, v_new.aim, v_new.end_purpose, coalesce(v_new.mastery, 0), v_new.memo, coalesce(v_new.archived, false)
    )
    returning id into v_id;
  else
    select * into v_old from public.sf6_sequences where id = p_id for update;
    if not found or p_updated_at is null or v_old.updated_at is distinct from p_updated_at then
      raise exception 'SF6_CONFLICT';
    end if;
    v_new := jsonb_populate_record(v_old, p_row);
    update public.sf6_sequences
    set kind = v_new.kind, character = v_new.character, title = v_new.title, notation = v_new.notation,
        startup = v_new.startup, damage = v_new.damage, drive_cost = v_new.drive_cost, sa_cost = v_new.sa_cost,
        position = v_new.position, layering = v_new.layering, aim = v_new.aim, end_purpose = v_new.end_purpose,
        mastery = v_new.mastery, memo = v_new.memo, archived = v_new.archived, updated_at = now()
    where id = p_id;
    v_id := p_id;
  end if;

  if p_starts is not null then
    delete from public.sf6_sequence_starts where sequence_id = v_id;
    for v_ref in select value from jsonb_array_elements(p_starts) loop
      insert into public.sf6_sequence_starts (sequence_id, situation_id)
      values (v_id, public.sf6_resolve_situation(v_new.character, v_ref))
      on conflict do nothing;
    end loop;
    if not exists (select 1 from public.sf6_sequence_starts where sequence_id = v_id) then
      raise exception 'SF6_STARTS_REQUIRED';
    end if;
  end if;

  if p_results is not null then
    delete from public.sf6_sequence_results where sequence_id = v_id;
    for v_result in select value from jsonb_array_elements(p_results) loop
      insert into public.sf6_sequence_results (sequence_id, kind, opponent_action, outcome, next_situation_id)
      values (
        v_id,
        v_result ->> 'kind',
        v_result ->> 'opponent_action',
        v_result ->> 'outcome',
        case when coalesce(jsonb_typeof(v_result -> 'next'), 'null') = 'null' then null
          else public.sf6_resolve_situation(v_new.character, v_result -> 'next') end
      );
    end loop;
  end if;

  -- A situation of another character cannot be used (also stops changing the character of a sequence in use).
  if exists (
    select 1 from public.sf6_sequence_starts st join public.sf6_situations s on s.id = st.situation_id
    where st.sequence_id = v_id and s.character is not null and s.character <> v_new.character
    union all
    select 1 from public.sf6_sequence_results r join public.sf6_situations s on s.id = r.next_situation_id
    where r.sequence_id = v_id and s.character is not null and s.character <> v_new.character
  ) then
    raise exception 'SF6_SITUATION_CHARACTER';
  end if;
  return v_id;
end;
$$;

-- Deletes a sequence and removes it from every drill's chain (sequence_ids has no foreign key).
create or replace function public.sf6_delete_sequence(p_id bigint)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
begin
  update public.sf6_drills
  set sequence_ids = array_remove(sequence_ids, p_id), updated_at = now()
  where p_id = any(sequence_ids);
  delete from public.sf6_sequences where id = p_id;
  if not found then
    raise exception 'SF6_NOT_FOUND';
  end if;
  return p_id;
end;
$$;

-- A situation in use keeps its kind and character, so the sequences using it stay valid
-- (otherwise their next save fails with SF6_SITUATION_CHARACTER). Making a trigger shared by every character is allowed.
create or replace function public.sf6_situations_guard_update()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if (new.kind is distinct from old.kind or new.character is distinct from old.character)
     and not (new.kind = old.kind and new.character is null)
     and (exists (select 1 from public.sf6_sequence_starts where situation_id = old.id)
       or exists (select 1 from public.sf6_sequence_results where next_situation_id = old.id)) then
    raise exception 'SF6_SITUATION_IN_USE';
  end if;
  return new;
end;
$$;

-- The initial triggers (preset_key) drive punish ordering and drill presets, so they can be archived or renamed
-- but not deleted.
create or replace function public.sf6_situations_guard_delete()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if old.preset_key is not null then
    raise exception 'SF6_PRESET_SITUATION';
  end if;
  return old;
end;
$$;

drop trigger if exists sf6_situations_guard_update on public.sf6_situations;
create trigger sf6_situations_guard_update
  before update on public.sf6_situations
  for each row execute function public.sf6_situations_guard_update();
drop trigger if exists sf6_situations_guard_delete on public.sf6_situations;
create trigger sf6_situations_guard_delete
  before delete on public.sf6_situations
  for each row execute function public.sf6_situations_guard_delete();

-- Copies sf6_combos / sf6_setplays (and drills' combo_id / setplay_id) into the new tables. Rows already copied
-- (legacy_*_id) are skipped, so calling it again only copies what was added since. Returns how many rows were added.
-- Dropped in phase 2.
create or replace function public.sf6_copy_legacy()
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_before jsonb;
  v_drills integer;
  v_combo record;
  v_setplay record;
  v_tag text;
  v_tags text[];
  v_sequence_id bigint;
  v_situation_id bigint;
  v_state_id bigint;
  v_combo_id bigint;
  v_combo_sequence_id bigint;
  v_end public.sf6_situations%rowtype;
  v_start public.sf6_situations%rowtype;
  v_name text;
begin
  v_before := jsonb_build_object(
    'situations', (select count(*) from public.sf6_situations),
    'sequences', (select count(*) from public.sf6_sequences),
    'starts', (select count(*) from public.sf6_sequence_starts),
    'results', (select count(*) from public.sf6_sequence_results));

  -- a. combos -> sequences (kind combo). burnout_ok is not copied (burnout is judged from the Drive cost).
  for v_combo in
    select c.* from public.sf6_combos c
    where not exists (select 1 from public.sf6_sequences s where s.legacy_combo_id = c.id)
    order by c.id
  loop
    insert into public.sf6_sequences (
      kind, character, title, notation, startup, damage, drive_cost, sa_cost, position, layering, aim, end_purpose,
      mastery, memo, archived, legacy_combo_id, legacy_copied_at, created_at, updated_at
    ) values (
      'combo', v_combo.character, v_combo.title, v_combo.notation, null, v_combo.damage, v_combo.drive_cost, v_combo.sa_cost,
      v_combo.position, null, null, v_combo.end_purpose, v_combo.mastery, v_combo.memo, v_combo.archived,
      v_combo.id, now(), v_combo.created_at, v_combo.updated_at
    )
    returning id into v_sequence_id;

    v_tags := case when cardinality(v_combo.situations) = 0 then array['未分類'] else v_combo.situations end;
    foreach v_tag in array v_tags loop
      select id into v_situation_id from public.sf6_situations
      where kind = 'trigger' and name = v_tag and (character = v_combo.character or character is null)
      order by (character is null), id
      limit 1;
      if v_situation_id is null then
        -- The previous screen listed custom situations for every character, so they become shared triggers.
        insert into public.sf6_situations (character, kind, name) values (null, 'trigger', v_tag)
        returning id into v_situation_id;
      end if;
      insert into public.sf6_sequence_starts (sequence_id, situation_id) values (v_sequence_id, v_situation_id)
      on conflict do nothing;
    end loop;

    if v_combo.end_advantage is not null then
      v_state_id := public.sf6_resolve_situation(v_combo.character, jsonb_build_object('state', jsonb_build_object(
        'advantage', v_combo.end_advantage, 'position', v_combo.position, 'recovery', v_combo.recovery,
        'name', regexp_replace(v_combo.title, '^.*\s', '') || '締め後')));
      insert into public.sf6_sequence_results (sequence_id, kind, next_situation_id) values (v_sequence_id, 'hit', v_state_id);
    end if;
  end loop;

  -- b. set plays -> sequences (kind setplay), starting from their own knockdown state
  for v_setplay in
    select p.* from public.sf6_setplays p
    where not exists (select 1 from public.sf6_sequences s where s.legacy_setplay_id = p.id)
    order by p.id
  loop
    insert into public.sf6_sequences (
      kind, character, title, notation, startup, damage, drive_cost, sa_cost, position, layering, aim, end_purpose,
      mastery, memo, archived, legacy_setplay_id, legacy_copied_at, created_at, updated_at
    ) values (
      'setplay', v_setplay.character, v_setplay.title, v_setplay.notation, null, null, 0, 0,
      v_setplay.position, v_setplay.layering, v_setplay.aim, null, v_setplay.mastery, v_setplay.memo, v_setplay.archived,
      v_setplay.id, now(), v_setplay.created_at, v_setplay.updated_at
    )
    returning id into v_sequence_id;

    v_name := null;
    if cardinality(v_setplay.combo_ids) > 0 then
      select regexp_replace(c.title, '^.*\s', '') || '締め後' into v_name
      from public.sf6_combos c where c.id = v_setplay.combo_ids[1];
    end if;
    v_state_id := public.sf6_resolve_situation(v_setplay.character, jsonb_build_object('state', jsonb_build_object(
      'advantage', v_setplay.start_advantage, 'position', v_setplay.position, 'recovery', v_setplay.recovery,
      'name', v_name)));
    insert into public.sf6_sequence_starts (sequence_id, situation_id) values (v_sequence_id, v_state_id)
    on conflict do nothing;

    insert into public.sf6_sequence_results (sequence_id, kind, opponent_action, outcome)
    select v_sequence_id, 'opponent', o.key, o.value
    from jsonb_each_text(v_setplay.outcomes) as o
    where o.key in ('reversal', 'backdash', 'jump', 'tech', 'delay_tech', 'parry', 'drive_reversal')
      and o.value in ('win', 'lose')
    order by o.key;
    if v_setplay.back_roll_ok in ('ok', 'ng') then
      insert into public.sf6_sequence_results (sequence_id, kind, opponent_action, outcome)
      values (v_sequence_id, 'opponent', 'back_roll', case v_setplay.back_roll_ok when 'ok' then 'win' else 'lose' end);
    end if;

    select * into v_start from public.sf6_situations where id = v_state_id;

    -- c. combos the set play was linked to
    foreach v_combo_id in array v_setplay.combo_ids loop
      select s.id into v_combo_sequence_id
      from public.sf6_sequences s
      join public.sf6_combos c on c.id = s.legacy_combo_id
      where s.legacy_combo_id = v_combo_id and c.character = v_setplay.character;
      continue when v_combo_sequence_id is null;

      select st.* into v_end
      from public.sf6_sequence_results r join public.sf6_situations st on st.id = r.next_situation_id
      where r.sequence_id = v_combo_sequence_id and r.kind = 'hit' and st.kind = 'state';
      if v_end.id is not null then
        -- The route shows it as "fits" / "near" already; otherwise keep the link the user made explicitly.
        if not (v_end.character = v_start.character
                and v_end.recovery is not distinct from v_start.recovery
                and (v_end.position = 'anywhere' or v_start.position = 'anywhere' or v_end.position = v_start.position)
                and abs(v_end.advantage - v_start.advantage) <= 2) then
          insert into public.sf6_sequence_starts (sequence_id, situation_id) values (v_sequence_id, v_end.id)
          on conflict do nothing;
        end if;
      elsif not exists (select 1 from public.sf6_sequence_results where sequence_id = v_combo_sequence_id and kind = 'hit') then
        insert into public.sf6_sequence_results (sequence_id, kind, next_situation_id) values (v_combo_sequence_id, 'hit', v_state_id);
      end if;
    end loop;

    -- d. follow-up combo after the set play hits
    if v_setplay.follow_combo_id is not null then
      select s.id into v_combo_sequence_id from public.sf6_sequences s where s.legacy_combo_id = v_setplay.follow_combo_id;
      if v_combo_sequence_id is not null then
        insert into public.sf6_situations (character, kind, name)
        values (v_setplay.character, 'trigger', left(v_setplay.title, 56) || ' ヒット')
        on conflict ((coalesce(character, '')), name) where kind = 'trigger' do update set archived = false
        returning id into v_situation_id;
        insert into public.sf6_sequence_results (sequence_id, kind, next_situation_id) values (v_sequence_id, 'hit', v_situation_id);
        insert into public.sf6_sequence_starts (sequence_id, situation_id) values (v_combo_sequence_id, v_situation_id)
        on conflict do nothing;
      end if;
    end if;
  end loop;

  -- e. drills: combo_id / setplay_id -> sequence_ids
  update public.sf6_drills d
  set sequence_ids = array[s.id]
  from public.sf6_sequences s
  where d.sequence_ids = '{}'
    and ((d.combo_id is not null and s.legacy_combo_id = d.combo_id)
      or (d.combo_id is null and d.setplay_id is not null and s.legacy_setplay_id = d.setplay_id));
  get diagnostics v_drills = row_count;

  return jsonb_build_object(
    'situations', (select count(*) from public.sf6_situations) - (v_before ->> 'situations')::bigint,
    'sequences', (select count(*) from public.sf6_sequences) - (v_before ->> 'sequences')::bigint,
    'starts', (select count(*) from public.sf6_sequence_starts) - (v_before ->> 'starts')::bigint,
    'results', (select count(*) from public.sf6_sequence_results) - (v_before ->> 'results')::bigint,
    'drills', v_drills);
end;
$$;

