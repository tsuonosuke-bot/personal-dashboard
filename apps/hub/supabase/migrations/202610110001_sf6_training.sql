-- SF6 page: combo book, cautions, practice drills and match reviews for Street Fighter 6.
-- Only the Hub's server-side API (service_role) reads and writes these tables.

create table if not exists public.sf6_combos (
  id bigint generated by default as identity primary key,
  character text not null check (char_length(character) between 1 and 40),
  title text not null check (char_length(title) between 1 and 120),
  notation text not null check (char_length(notation) between 1 and 1000),
  position text not null default 'anywhere' check (position in ('anywhere', 'midscreen', 'corner')),
  damage integer check (damage is null or damage between 0 and 20000),
  drive_cost smallint not null default 0 check (drive_cost between 0 and 6),
  sa_cost smallint not null default 0 check (sa_cost between 0 and 3),
  mastery smallint not null default 0 check (mastery between 0 and 3),
  memo text check (memo is null or char_length(memo) between 1 and 2000),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sf6_notes (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('matchup', 'self', 'general')),
  opponent text check (opponent is null or char_length(opponent) between 1 and 40),
  body text not null check (char_length(body) between 1 and 2000),
  pinned boolean not null default false,
  resolved boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((category = 'matchup') = (opponent is not null))
);

create table if not exists public.sf6_drills (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 200),
  detail text check (detail is null or char_length(detail) between 1 and 2000),
  combo_id bigint references public.sf6_combos(id) on delete set null,
  status text not null default 'active' check (status in ('active', 'done')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sf6_drill_logs (
  id bigint generated by default as identity primary key,
  drill_id bigint not null references public.sf6_drills(id) on delete cascade,
  practiced_on date not null,
  attempts integer check (attempts is null or attempts between 1 and 10000),
  successes integer check (successes is null or successes between 0 and 10000),
  note text check (note is null or char_length(note) between 1 and 2000),
  created_at timestamptz not null default now(),
  check ((attempts is null) = (successes is null)),
  check (successes is null or successes <= attempts)
);

create table if not exists public.sf6_matches (
  id bigint generated by default as identity primary key,
  played_on date not null,
  my_character text not null check (char_length(my_character) between 1 and 40),
  opponent text not null check (char_length(opponent) between 1 and 40),
  result text not null check (result in ('win', 'lose', 'draw')),
  mode text not null default 'ranked' check (mode in ('ranked', 'casual', 'battle_hub', 'tournament', 'other')),
  good text check (good is null or char_length(good) between 1 and 2000),
  bad text check (bad is null or char_length(bad) between 1 and 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists sf6_combos_character_idx on public.sf6_combos (character, archived, created_at desc);
create index if not exists sf6_notes_category_idx on public.sf6_notes (category, resolved, created_at desc);
create index if not exists sf6_drills_combo_id_idx on public.sf6_drills (combo_id);
create index if not exists sf6_drill_logs_drill_id_idx on public.sf6_drill_logs (drill_id, practiced_on desc);
create index if not exists sf6_matches_played_on_idx on public.sf6_matches (played_on desc, id desc);

alter table public.sf6_combos enable row level security;
alter table public.sf6_notes enable row level security;
alter table public.sf6_drills enable row level security;
alter table public.sf6_drill_logs enable row level security;
alter table public.sf6_matches enable row level security;

revoke all on table public.sf6_combos, public.sf6_notes, public.sf6_drills, public.sf6_drill_logs, public.sf6_matches
  from public, anon, authenticated;
grant select, insert, update, delete on table public.sf6_combos, public.sf6_notes, public.sf6_drills, public.sf6_drill_logs, public.sf6_matches
  to service_role;

comment on table public.sf6_combos is 'SF6 combo book. drive_cost is in Drive gauge bars, sa_cost in SA gauge bars, mastery 0 (untried) to 3 (works in matches).';
comment on table public.sf6_notes is 'SF6 cautions: matchup notes (opponent required), own bad habits (self) and general reminders.';
comment on table public.sf6_drills is 'SF6 practice menu. combo_id links a drill to the combo it trains.';
comment on table public.sf6_drill_logs is 'One training-mode session for a drill; attempts/successes are optional but come as a pair.';
comment on table public.sf6_matches is 'SF6 match reviews: what went well (good) and what to fix (bad).';
