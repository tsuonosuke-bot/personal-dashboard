-- SF6: situations and conditions for combos, what happens after the ender, set plays (okizeme),
-- and training-mode settings / best streaks for practice. Existing rows keep working:
-- drive_cost widens to half bars, sa_cost gains 4 = CA, every new column is nullable or defaulted.

-- ① situations (how the combo starts) and conditions (gauge, burnout)
alter table public.sf6_combos
  add column if not exists situations text[] not null default '{}'
    check (cardinality(situations) <= 12),
  add column if not exists burnout_ok boolean not null default false;

alter table public.sf6_combos alter column drive_cost type numeric(2,1) using drive_cost::numeric(2,1);
alter table public.sf6_combos drop constraint if exists sf6_combos_drive_cost_check;
alter table public.sf6_combos add constraint sf6_combos_drive_cost_check
  check (drive_cost between 0 and 6 and drive_cost * 2 = trunc(drive_cost * 2));
alter table public.sf6_combos drop constraint if exists sf6_combos_sa_cost_check;
alter table public.sf6_combos add constraint sf6_combos_sa_cost_check check (sa_cost between 0 and 4);

-- ② after the ender
alter table public.sf6_combos
  add column if not exists end_advantage smallint check (end_advantage is null or end_advantage between -99 and 300),
  add column if not exists recovery text check (recovery is null or recovery in ('back_roll', 'no_back_roll', 'none')),
  add column if not exists end_purpose text check (end_purpose is null or end_purpose in ('damage', 'oki', 'carry'));

create index if not exists sf6_combos_situations_idx on public.sf6_combos using gin (situations);

-- ③ set plays
create table if not exists public.sf6_setplays (
  id bigint generated by default as identity primary key,
  character text not null check (char_length(character) between 1 and 40),
  title text not null check (char_length(title) between 1 and 120),
  combo_ids bigint[] not null default '{}' check (cardinality(combo_ids) <= 20),
  start_advantage smallint not null check (start_advantage between -99 and 300),
  position text not null default 'anywhere' check (position in ('anywhere', 'midscreen', 'corner')),
  recovery text not null default 'back_roll' check (recovery in ('back_roll', 'no_back_roll', 'none')),
  notation text not null check (char_length(notation) between 1 and 1000),
  layering text check (layering is null or layering in ('meaty', 'safe_jump', 'other')),
  aim text not null check (aim in ('strike', 'throw', 'shimmy')),
  back_roll_ok text not null default 'unknown' check (back_roll_ok in ('ok', 'ng', 'unknown')),
  outcomes jsonb not null default '{}'::jsonb check (jsonb_typeof(outcomes) = 'object'),
  follow_combo_id bigint references public.sf6_combos(id) on delete set null,
  mastery smallint not null default 0 check (mastery between 0 and 3),
  memo text check (memo is null or char_length(memo) between 1 and 2000),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists sf6_setplays_character_idx on public.sf6_setplays (character, archived, created_at);
create index if not exists sf6_setplays_follow_combo_id_idx on public.sf6_setplays (follow_combo_id);

alter table public.sf6_setplays enable row level security;
revoke all on table public.sf6_setplays from public, anon, authenticated;
grant select, insert, update, delete on table public.sf6_setplays to service_role;

-- ④ practice: drills can train a set play and remember the training-mode settings
alter table public.sf6_drills
  add column if not exists setplay_id bigint references public.sf6_setplays(id) on delete set null,
  add column if not exists guard_setting text check (guard_setting is null or guard_setting in ('none', 'all', 'random')),
  add column if not exists counter_setting text check (counter_setting is null or counter_setting in ('normal', 'counter', 'punish_counter', 'random')),
  add column if not exists recovery_setting text check (recovery_setting is null or recovery_setting in ('neutral', 'back', 'random')),
  add column if not exists reversal_recorded boolean not null default false;

create index if not exists sf6_drills_setplay_id_idx on public.sf6_drills (setplay_id);

alter table public.sf6_drill_logs
  add column if not exists best_streak integer check (best_streak is null or best_streak between 0 and 10000);
alter table public.sf6_drill_logs drop constraint if exists sf6_drill_logs_best_streak_le_successes;
alter table public.sf6_drill_logs add constraint sf6_drill_logs_best_streak_le_successes
  check (best_streak is null or (successes is not null and best_streak <= successes));

comment on column public.sf6_combos.situations is 'How the combo starts (punish, hit confirm, anti-air, ...). Preset labels or user-defined ones.';
comment on column public.sf6_combos.burnout_ok is 'True when the combo needs no Drive gauge and still works while burned out.';
comment on column public.sf6_combos.sa_cost is 'SA used: 0 none, 1-3 SA level, 4 = Critical Art.';
comment on column public.sf6_combos.end_advantage is 'Frame advantage after the ender, read from the training-mode frame meter.';
comment on column public.sf6_combos.recovery is 'back_roll: opponent may back-roll; no_back_roll: knockdown without back roll; none: no knockdown.';
comment on table public.sf6_setplays is 'SF6 okizeme. start_advantage/position/recovery describe the knockdown it starts from; outcomes maps opponent options to win/lose/unknown.';
comment on column public.sf6_drills.setplay_id is 'Set play this drill trains (a drill trains a combo, a set play, or neither).';
comment on column public.sf6_drill_logs.best_streak is 'Longest run of consecutive successes in the session; 10 in a row on random settings marks stage 3 mastery.';
