create extension if not exists pg_cron with schema extensions;
do $$ begin
  if not exists (select 1 from cron.job where jobname = 'materialize-recurring-expenses-jst') then
    perform cron.schedule(
      'materialize-recurring-expenses-jst',
      '10 15 * * *',
      'select public.materialize_recurring_expenses();'
    );
  end if;
end $$;
